import React, { useState } from 'react';
import { AnalysisResult, FrameAnalysis } from '../types';
import { Download, RefreshCw, ZoomIn, Activity, Sparkles, Film, ScanFace, Clock, ShieldAlert, ShieldCheck, Layers, FileDown } from 'lucide-react';

interface AnalysisResultSectionProps {
  result: AnalysisResult;
  onRunAgain: () => void;
  onDownloadDocxPlan: () => void;
}

export const AnalysisResultSection: React.FC<AnalysisResultSectionProps> = ({
  result,
  onRunAgain,
  onDownloadDocxPlan,
}) => {
  const [selectedFrameIndex, setSelectedFrameIndex] = useState<number>(0);
  const [activeLayer, setActiveLayer] = useState<'heatmap' | 'bbox' | 'raw'>('heatmap');
  const [inspectModalFrame, setInspectModalFrame] = useState<FrameAnalysis | null>(null);

  const isDeepfake = result.verdict === 'DEEPFAKE';
  const displayFrames = result.frames.slice(0, 5); // 5 frames matching wireframe item 5
  const currentFrame = result.frames[selectedFrameIndex] || result.frames[0];

  const handleExportSummary = () => {
    const reportText = `DEEPFAKE DETECTIVE FORENSIC ANALYSIS REPORT
--------------------------------------------------
File: ${result.fileName} (${result.fileSizeMb} MB)
Analyzed: ${new Date(result.analyzedAt).toLocaleString()}
Verdict: ${result.verdict}
Confidence Score: ${result.confidenceScore}%
Overall Fake Probability: ${(result.overallFakeProbability * 100).toFixed(1)}%
Frames Analyzed: ${result.totalFrames}
Faces Detected: ${result.detectedFaces}
Processing Latency: ${result.processingTimeSec}s
Detector Architecture: ${result.faceDetectorUsed}
Feature Backbone: ${result.backboneUsed}
Findings: ${result.summaryNote}
--------------------------------------------------
Generated by AI Media Forensics & Biometric Security Division
`;
    const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Deepfake_Report_${result.fileName.replace(/\.[^/.]+$/, '')}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <section id="results" className="py-20 bg-slate-900/60 border-t border-white/10 relative overflow-hidden">
      {/* Background ambient lighting */}
      <div className={`absolute top-1/4 right-1/4 w-[600px] h-[300px] blur-[150px] pointer-events-none -z-10 ${
        isDeepfake ? 'bg-rose-600/15' : 'bg-emerald-600/15'
      }`} />

      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 relative z-10">
        
        {/* Section Header with Quick Actions */}
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 pb-6 border-b border-white/10 mb-8">
          <div>
            <div className="flex items-center space-x-2.5">
              <span className="px-3 py-1 rounded-full bg-indigo-950 border border-indigo-500/50 text-indigo-300 font-mono text-xs font-bold shadow-sm">
                SCAN ID: {result.id.toUpperCase()}
              </span>
              <span className="text-xs text-slate-300 font-mono">
                {new Date(result.analyzedAt).toLocaleTimeString()}
              </span>
            </div>
            <h2 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight mt-1.5 flex items-center space-x-2">
              <span>Forensic Analysis Results</span>
              <span className="text-slate-400 font-normal text-base">({result.fileName})</span>
            </h2>
          </div>

          <div className="flex flex-wrap items-center gap-2 sm:gap-3">
            <button
              onClick={onRunAgain}
              className="inline-flex items-center space-x-1.5 px-4 py-2 rounded-xl border border-slate-700 bg-slate-800/90 hover:bg-slate-800 text-slate-200 hover:text-white text-xs font-bold shadow-md transition-all cursor-pointer"
            >
              <RefreshCw className="w-3.5 h-3.5" />
              <span>Analyze Another</span>
            </button>
            <button
              onClick={onDownloadDocxPlan}
              className="inline-flex items-center space-x-1.5 px-4 py-2 rounded-xl border border-indigo-500/50 bg-indigo-950/80 hover:bg-indigo-900 text-indigo-200 text-xs font-bold shadow-md transition-all cursor-pointer"
              title="Download 40% Milestone Plan DOCX"
            >
              <FileDown className="w-3.5 h-3.5 text-indigo-400" />
              <span>Milestone Plan (.docx)</span>
            </button>
            <button
              onClick={handleExportSummary}
              className="inline-flex items-center space-x-1.5 px-4 py-2 rounded-xl bg-gradient-to-r from-indigo-600 to-teal-500 hover:from-indigo-500 hover:to-teal-400 text-white text-xs font-bold shadow-lg shadow-indigo-600/30 transition-all cursor-pointer ring-1 ring-white/20"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Export Report</span>
            </button>
          </div>
        </div>

        {/* Top Summary Block */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-stretch mb-10">
          
          {/* Gauge / Confidence Meter Card */}
          <div className="lg:col-span-5 bg-slate-900/95 border border-white/15 rounded-3xl p-6 sm:p-7 flex flex-col justify-between shadow-2xl backdrop-blur-xl relative overflow-hidden ring-1 ring-white/10">
            
            <div className="flex items-center justify-between mb-4">
              <span className="text-xs font-bold text-slate-300 uppercase tracking-wider flex items-center space-x-1.5">
                <Layers className="w-3.5 h-3.5 text-indigo-400" />
                <span>Classification Verdict</span>
              </span>
              <span
                className={`px-3.5 py-1.5 rounded-full text-xs font-extrabold tracking-wider font-mono flex items-center space-x-1.5 shadow-md ${
                  isDeepfake
                    ? 'bg-rose-950/95 text-rose-300 border border-rose-500/60 shadow-rose-950/50'
                    : 'bg-emerald-950/95 text-emerald-300 border border-emerald-500/60 shadow-emerald-950/50'
                }`}
              >
                {isDeepfake ? <ShieldAlert className="w-3.5 h-3.5 text-rose-400" /> : <ShieldCheck className="w-3.5 h-3.5 text-emerald-400" />}
                <span>{result.verdict}</span>
              </span>
            </div>

            {/* Circular Gauge Meter Visual */}
            <div className="py-4 flex flex-col items-center justify-center relative">
              <div className="relative w-48 h-48 flex items-center justify-center">
                {/* SVG Gauge Circle */}
                <svg className="w-full h-full transform -rotate-90" viewBox="0 0 100 100">
                  <circle
                    cx="50"
                    cy="50"
                    r="40"
                    stroke="#1e293b"
                    strokeWidth="9"
                    fill="transparent"
                  />
                  <circle
                    cx="50"
                    cy="50"
                    r="40"
                    stroke={isDeepfake ? '#f43f5e' : '#10b981'}
                    strokeWidth="9"
                    strokeDasharray={251.2}
                    strokeDashoffset={251.2 * (1 - result.confidenceScore / 100)}
                    strokeLinecap="round"
                    fill="transparent"
                    style={{
                      filter: isDeepfake ? 'drop-shadow(0 0 8px rgba(244,63,94,0.6))' : 'drop-shadow(0 0 8px rgba(16,185,129,0.6))',
                    }}
                    className="transition-all duration-1000 ease-out"
                  />
                </svg>

                {/* Score Text in Center */}
                <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
                  <span className={`text-5xl font-extrabold tracking-tight ${isDeepfake ? 'text-rose-400' : 'text-emerald-400'}`}>
                    {result.confidenceScore}%
                  </span>
                  <span className="text-[11px] font-bold text-slate-300 uppercase tracking-wider mt-1">
                    confidence score
                  </span>
                  <span className="text-[10px] text-slate-400 font-mono mt-0.5">
                    Calibrated Sigmoid Output
                  </span>
                </div>
              </div>
            </div>

            {/* Bottom Verdict Text */}
            <div className="mt-4 p-3.5 bg-slate-950/70 rounded-2xl border border-white/10 text-xs text-slate-200 leading-relaxed text-center font-medium">
              {result.summaryNote}
            </div>
          </div>

          {/* Metrics Pills & Probability Timeline */}
          <div className="lg:col-span-7 flex flex-col justify-between space-y-4">
            
            {/* 3 Metrics Cards */}
            <div className="grid grid-cols-3 gap-3">
              <div className="bg-slate-900/90 border border-white/10 rounded-2xl p-4 text-center shadow-lg hover:border-indigo-500/40 transition-all">
                <div className="w-8 h-8 rounded-xl bg-indigo-950/80 border border-indigo-600/40 flex items-center justify-center text-indigo-400 mx-auto mb-1.5">
                  <Film className="w-4 h-4" />
                </div>
                <p className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">{result.totalFrames}</p>
                <p className="text-[11px] font-bold text-slate-300 mt-0.5">Frames Analyzed</p>
                <p className="text-[10px] text-slate-400 font-mono mt-0.5">4 FPS Sampling</p>
              </div>

              <div className="bg-slate-900/90 border border-white/10 rounded-2xl p-4 text-center shadow-lg hover:border-teal-500/40 transition-all">
                <div className="w-8 h-8 rounded-xl bg-teal-950/80 border border-teal-600/40 flex items-center justify-center text-teal-400 mx-auto mb-1.5">
                  <ScanFace className="w-4 h-4" />
                </div>
                <p className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">{result.detectedFaces}</p>
                <p className="text-[11px] font-bold text-slate-300 mt-0.5">Faces Detected</p>
                <p className="text-[10px] text-slate-400 font-mono mt-0.5">YOLOv12 Localized</p>
              </div>

              <div className="bg-slate-900/90 border border-white/10 rounded-2xl p-4 text-center shadow-lg hover:border-indigo-500/40 transition-all">
                <div className="w-8 h-8 rounded-xl bg-indigo-950/80 border border-indigo-600/40 flex items-center justify-center text-indigo-400 mx-auto mb-1.5">
                  <Clock className="w-4 h-4" />
                </div>
                <p className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">{result.processingTimeSec}s</p>
                <p className="text-[11px] font-bold text-slate-300 mt-0.5">Processing Time</p>
                <p className="text-[10px] text-slate-400 font-mono mt-0.5">GPU/Wasm Accelerated</p>
              </div>
            </div>

            {/* Frame-by-frame fake probability scrubber */}
            <div className="bg-slate-900/90 border border-white/10 rounded-2xl p-5 shadow-xl">
              <div className="flex flex-wrap items-center justify-between gap-2 mb-3">
                <div className="flex items-center space-x-2">
                  <span className="text-xs font-bold text-slate-200 uppercase tracking-wider flex items-center space-x-1.5">
                    <Activity className="w-3.5 h-3.5 text-indigo-400" />
                    <span>Fake Probability Timeline</span>
                  </span>
                  <span className="text-[10px] font-mono text-amber-400 bg-amber-950/60 border border-amber-500/30 px-2 py-0.5 rounded-full">
                    Threshold: 50%
                  </span>
                </div>
                <span className="text-xs font-mono text-teal-300 font-bold bg-slate-950 px-2.5 py-1 rounded-lg border border-white/10 shadow-xs">
                  Frame #{currentFrame.frameNumber} ({currentFrame.timestamp})
                </span>
              </div>

              {/* Bar Scrubber Chart */}
              <div className="h-28 flex items-end space-x-1.5 pt-4 pb-2 border-b border-slate-800 relative">
                {/* 50% Threshold Guide Line */}
                <div className="absolute inset-x-0 bottom-1/2 border-b border-dashed border-amber-500/50 pointer-events-none z-0" />

                {result.frames.map((frame, idx) => {
                  const heightPercent = Math.max(14, Math.round(frame.fakeProbability * 100));
                  const isSelected = selectedFrameIndex === idx;
                  const isAboveThreshold = frame.fakeProbability >= 0.5;

                  return (
                    <div
                      key={frame.frameNumber}
                      onClick={() => setSelectedFrameIndex(idx)}
                      title={`Frame #${frame.frameNumber}: ${(frame.fakeProbability * 100).toFixed(1)}% Fake Prob`}
                      className="flex-1 flex flex-col items-center justify-end h-full cursor-pointer group relative z-10"
                    >
                      <div
                        className={`w-full rounded-t-sm transition-all duration-150 ${
                          isSelected
                            ? 'ring-2 ring-white scale-y-105 shadow-md shadow-white/30'
                            : ''
                        } ${
                          isAboveThreshold
                            ? 'bg-rose-500 hover:bg-rose-400'
                            : 'bg-emerald-500 hover:bg-emerald-400'
                        }`}
                        style={{ height: `${heightPercent}%` }}
                      />
                    </div>
                  );
                })}
              </div>

              <div className="flex items-center justify-between text-[11px] text-slate-400 font-mono mt-2.5">
                <span>00:00 (Start)</span>
                <span className="text-slate-300 font-bold">Interactive Timeline (Click bar to inspect)</span>
                <span>00:08 (End)</span>
              </div>
            </div>

            {/* Inspector Tip */}
            <div className="p-3.5 bg-indigo-950/70 rounded-2xl border border-indigo-500/40 flex items-center justify-between text-xs text-indigo-100 shadow-md">
              <div className="flex items-center space-x-2.5">
                <Sparkles className="w-4 h-4 text-teal-400 shrink-0" />
                <span>
                  Current Inspection: <strong>Frame #{currentFrame.frameNumber}</strong> • Anomaly Probability: <strong className="text-white font-mono">{(currentFrame.fakeProbability * 100).toFixed(1)}%</strong>
                </span>
              </div>
              <span className="text-[11px] text-teal-300 font-bold font-mono bg-slate-950/80 px-2 py-0.5 rounded border border-white/10 truncate max-w-[220px]">
                {currentFrame.detectedArtifacts[0]}
              </span>
            </div>

          </div>

        </div>

        {/* Grad-CAM Heatmaps on Video Frames */}
        <div className="mt-12 pt-8 border-t border-white/10">
          
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-6">
            <div>
              <h3 className="text-xl sm:text-2xl font-extrabold text-white tracking-tight flex items-center space-x-2">
                <span>Grad-CAM heatmaps on video frames</span>
                <span className="text-xs px-2.5 py-0.5 rounded-full bg-indigo-950 text-indigo-300 border border-indigo-500/40 font-mono font-semibold">
                  5 Keyframes
                </span>
              </h3>
              <p className="text-xs sm:text-sm text-slate-300 mt-1">
                Thermal overlays localize pixel gradients contributing to the synthetic manipulation classification.
              </p>
            </div>

            {/* Layer Controls */}
            <div className="inline-flex rounded-xl bg-slate-950 p-1 text-xs border border-white/10 shadow-inner">
              <button
                onClick={() => setActiveLayer('heatmap')}
                className={`px-3.5 py-1.5 rounded-lg font-bold transition-all cursor-pointer ${
                  activeLayer === 'heatmap'
                    ? 'bg-indigo-600 text-white shadow-md'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                Grad-CAM Heatmap
              </button>
              <button
                onClick={() => setActiveLayer('bbox')}
                className={`px-3.5 py-1.5 rounded-lg font-bold transition-all cursor-pointer ${
                  activeLayer === 'bbox'
                    ? 'bg-slate-700 text-white shadow-md'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                YOLOv12 BBox
              </button>
              <button
                onClick={() => setActiveLayer('raw')}
                className={`px-3.5 py-1.5 rounded-lg font-bold transition-all cursor-pointer ${
                  activeLayer === 'raw'
                    ? 'bg-slate-700 text-white shadow-md'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                Raw Frame
              </button>
            </div>
          </div>

          {/* 5 Frames Row */}
          <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-5 gap-4">
            {displayFrames.map((frame, idx) => {
              const isSelected = selectedFrameIndex === idx;
              return (
                <div
                  key={frame.frameNumber}
                  onClick={() => {
                    setSelectedFrameIndex(idx);
                    setInspectModalFrame(frame);
                  }}
                  className={`group relative rounded-2xl overflow-hidden border cursor-pointer transition-all duration-200 select-none ${
                    isSelected
                      ? 'border-indigo-400 ring-4 ring-indigo-500/40 shadow-2xl scale-[1.02]'
                      : 'border-white/10 hover:border-slate-500 bg-slate-900 shadow-md hover:-translate-y-1'
                  }`}
                >
                  {/* Aspect Ratio Container */}
                  <div className="relative aspect-square bg-black flex items-center justify-center overflow-hidden">
                    
                    {/* Underlying Face Image */}
                    <img
                      src={frame.sampleImage}
                      alt={`Frame ${frame.frameNumber}`}
                      loading="lazy"
                      decoding="async"
                      className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300 brightness-95"
                    />

                    {/* Grad-CAM Thermal Hotspot */}
                    {activeLayer === 'heatmap' && (
                      <div
                        className="absolute pointer-events-none rounded-full blur-md opacity-85 transition-opacity"
                        style={{
                          left: `${frame.gradCamRegion.cx}%`,
                          top: `${frame.gradCamRegion.cy}%`,
                          width: `${frame.gradCamRegion.radius * 2.5}%`,
                          height: `${frame.gradCamRegion.radius * 2.5}%`,
                          transform: 'translate(-50%, -50%)',
                          background: isDeepfake
                            ? 'radial-gradient(circle, rgba(239,68,68,0.92) 0%, rgba(245,158,11,0.7) 45%, rgba(59,130,246,0.3) 80%, transparent 100%)'
                            : 'radial-gradient(circle, rgba(16,185,129,0.8) 0%, rgba(59,130,246,0.4) 60%, transparent 100%)',
                        }}
                      />
                    )}

                    {/* YOLOv12 Bounding Box */}
                    {(activeLayer === 'bbox' || activeLayer === 'heatmap') && (
                      <div
                        className="absolute border-2 border-dashed border-emerald-400 pointer-events-none rounded-sm shadow-[0_0_10px_#34d399]"
                        style={{
                          left: `${frame.boundingBox.x}%`,
                          top: `${frame.boundingBox.y}%`,
                          width: `${frame.boundingBox.width}%`,
                          height: `${frame.boundingBox.height}%`,
                        }}
                      />
                    )}

                    {/* Frame Badge */}
                    <div className="absolute top-2.5 left-2.5 px-2 py-0.5 rounded-lg bg-black/90 text-[10px] font-mono text-white border border-white/20 font-bold">
                      F#{frame.frameNumber}
                    </div>

                    {/* Zoom Icon on hover */}
                    <div className="absolute inset-0 bg-indigo-950/60 opacity-0 group-hover:opacity-100 flex flex-col items-center justify-center text-white transition-opacity gap-1 backdrop-blur-xs">
                      <ZoomIn className="w-6 h-6 drop-shadow-md text-teal-300" />
                      <span className="text-[10px] font-bold tracking-wider uppercase">Inspect Hotspot</span>
                    </div>
                  </div>

                  {/* Frame Footer Info */}
                  <div className="p-3 bg-slate-950 border-t border-white/10 text-xs">
                    <div className="flex items-center justify-between">
                      <span className="text-[11px] text-slate-300 font-mono font-medium">{frame.timestamp}</span>
                      <span
                        className={`text-[11px] font-extrabold font-mono px-1.5 py-0.5 rounded ${
                          frame.isFake 
                            ? 'text-rose-300 bg-rose-950/80 border border-rose-800/60' 
                            : 'text-emerald-300 bg-emerald-950/80 border border-emerald-800/60'
                        }`}
                      >
                        {(frame.fakeProbability * 100).toFixed(0)}% Fake
                      </span>
                    </div>
                  </div>
                </div>
              );
            })}
          </div>

        </div>

      </div>

      {/* Frame Inspection Zoom Modal */}
      {inspectModalFrame && (
        <div className="fixed inset-0 z-50 bg-slate-950/85 backdrop-blur-md flex items-center justify-center p-4 animate-in fade-in">
          <div className="bg-slate-900 rounded-3xl max-w-xl w-full p-6 sm:p-7 shadow-2xl border border-white/15 ring-1 ring-white/10">
            <div className="flex items-center justify-between pb-3.5 border-b border-white/10 mb-4">
              <div className="flex items-center space-x-2.5">
                <span className="w-3 h-3 rounded-full bg-teal-400 animate-pulse" />
                <h4 className="font-extrabold text-white text-base">
                  Forensic Micro-Inspection: Frame #{inspectModalFrame.frameNumber}
                </h4>
              </div>
              <button
                onClick={() => setInspectModalFrame(null)}
                className="text-slate-400 hover:text-white text-lg font-bold p-1 cursor-pointer"
              >
                ✕
              </button>
            </div>

            <div className="relative aspect-square max-h-[340px] mx-auto rounded-2xl overflow-hidden bg-black mb-4 flex items-center justify-center border border-white/15 shadow-2xl">
              <img
                src={inspectModalFrame.sampleImage}
                alt="Frame Zoom"
                className="w-full h-full object-cover brightness-95"
              />
              <div
                className="absolute pointer-events-none rounded-full blur-md opacity-90"
                style={{
                  left: `${inspectModalFrame.gradCamRegion.cx}%`,
                  top: `${inspectModalFrame.gradCamRegion.cy}%`,
                  width: `${inspectModalFrame.gradCamRegion.radius * 2.8}%`,
                  height: `${inspectModalFrame.gradCamRegion.radius * 2.8}%`,
                  transform: 'translate(-50%, -50%)',
                  background: isDeepfake
                    ? 'radial-gradient(circle, rgba(239,68,68,0.95) 0%, rgba(245,158,11,0.7) 45%, rgba(59,130,246,0.3) 80%, transparent 100%)'
                    : 'radial-gradient(circle, rgba(16,185,129,0.85) 0%, rgba(59,130,246,0.4) 60%, transparent 100%)',
                }}
              />
            </div>

            <div className="space-y-2.5 text-xs">
              <div className="p-3.5 rounded-2xl bg-slate-950 border border-white/10 space-y-1.5 shadow-inner">
                <p className="font-bold text-white flex items-center space-x-1.5">
                  <span className="w-2 h-2 rounded-full bg-rose-400" />
                  <span>Identified Synthesis Artifact:</span>
                </p>
                <p className="text-slate-300 font-mono text-xs">{inspectModalFrame.detectedArtifacts[0]}</p>
                <p className="text-teal-300 font-mono text-[11px] pt-1">
                  Target Coordinate: {inspectModalFrame.gradCamRegion.description}
                </p>
              </div>
            </div>

            <div className="mt-5 text-right">
              <button
                onClick={() => setInspectModalFrame(null)}
                className="px-5 py-2.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-white font-bold text-xs transition-colors cursor-pointer border border-white/10"
              >
                Close Inspector
              </button>
            </div>
          </div>
        </div>
      )}

    </section>
  );
};
